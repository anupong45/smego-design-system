import type { ReactNode } from 'react';
import { cn } from '../lib/cn';

/* ═══════════════════════════════════════════════════════════════════════════
   SME.GO · Main — เป้าของลิงก์ข้ามไปเนื้อหา (SC 2.4.1)
   ───────────────────────────────────────────────────────────────────────────
   ★★★ component นี้มีอยู่เพื่อ **ปิดรูที่ไม่มีเจ้าของ**

   `TopNav` render ลิงก์ข้ามไปเนื้อหาเป็นชิ้นแรกใน DOM ตาม SC 2.4.1 โดยชี้ไป
   `#main` (ปรับได้ด้วย `mainId`) — แต่ **ไม่มี component ไหนในไลบรารีประกาศ
   `id="main"`** มีแต่ในตัวอย่างในเอกสารและใน gallery

   ผลคือถ้าแอปลืม ลิงก์ข้ามจะเป็น **ลิงก์ตาย**: กด Tab ครั้งแรกเจอลิงก์
   กด Enter แล้วไม่มีอะไรเกิดขึ้น · เป็นความพังที่มองไม่เห็นด้วยตาเลย
   เพราะลิงก์ยังซ่อนอยู่จนกว่าจะโฟกัส และหน้าก็ยังดูปกติทุกอย่าง

   เอกสารเคยผลักภาระนี้ไปที่ "ชั้น 05 Templates" (`Grid.md` · `FilterPanel.md`)
   แต่คำตัดสิน 2026-07-29 คือ **ไม่ทำชั้น 05** — แอปประกอบหน้าเอง
   ภาระ SC 2.4.1 จึงต้องมีเจ้าของในชั้น 03 ไม่ใช่ค้างอยู่กับชั้นที่ไม่เกิด

   ★★ `tabIndex={-1}` **จำเป็น ไม่ใช่ของแถม**

   `<main>` ไม่ใช่ element ที่โฟกัสได้เอง · เบราว์เซอร์บางตัวเลื่อนหน้าไปที่
   fragment แต่ **ไม่ย้ายโฟกัส** ทำให้ Tab ครั้งถัดไปกลับไปที่ลิงก์ข้ามอีก
   วนอยู่อย่างนั้น — `tabIndex={-1}` ทำให้โฟกัสไปลงจริงโดยไม่เพิ่ม tab stop

   ★ ห้ามมีมากกว่าหนึ่งตัวต่อหน้า — `<main>` สองอันทำให้ landmark ซ้ำ
   axe ฟ้อง `landmark-one-main` และผู้ใช้ screen reader แยกไม่ออกว่าอันไหน
   คือเนื้อหาจริง
   ═══════════════════════════════════════════════════════════════════════════ */

export interface MainProps {
  children: ReactNode;
  /**
   * ต้องตรงกับ `mainId` ของ [`TopNav`](../navigation/TopNav.md)
   *
   * ค่าเริ่มต้นของทั้งสองตัวคือ `"main"` จึงเข้าคู่กันเองถ้าไม่แตะ
   */
  id?: string;
  className?: string;
}

export function Main({ children, id = 'main', className }: MainProps) {
  return (
    <main
      id={id}
      /* ★★ ดูหัวไฟล์ — ไม่มีบรรทัดนี้ ลิงก์ข้ามจะเลื่อนหน้าแต่ไม่ย้ายโฟกัส */
      tabIndex={-1}
      /* ★ ไม่มีวงโฟกัสให้เห็น เพราะผู้ใช้ไม่ได้ "โฟกัสที่เนื้อหา" เชิงความรู้สึก
         เขากระโดดมาที่นี่แล้วจะ Tab ต่อไปยัง element แรกในเนื้อหา
         การวาดวงรอบทั้งบล็อกเนื้อหาจะทำให้เข้าใจผิดว่าทั้งก้อนกดได้ */
      className={cn('outline-hidden', className)}
    >
      {children}
    </main>
  );
}

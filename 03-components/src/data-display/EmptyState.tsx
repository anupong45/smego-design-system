import type { ReactNode } from 'react';
import { cn } from '../lib/cn';

/* ═══════════════════════════════════════════════════════════════════════════
   SME.GO · EmptyState — ที่ว่างที่บอกทางออก
   ───────────────────────────────────────────────────────────────────────────
   สกัดออกมาจาก 3 ที่ที่เขียนซ้ำกันแทบ byte-identical:
   `Cart.tsx` · `Wishlist.tsx` · `SearchResult.tsx`

   ★★★ **`role="status"` เป็น opt-in ไม่ใช่ค่าเริ่มต้น** (ต่างจาก Astryx · D26)

   Astryx ตั้ง `role="status"` ตายตัว · เราทำไม่ได้เพราะ `SearchResult` มี
   คอมเมนต์กำกับไว้แล้วว่า**ห้าม**เป็น live region:

       "ไม่ใช่ live region — ข้อความจำนวนด้านบนประกาศไปแล้ว
        ถ้าประกาศซ้ำผู้ใช้จะได้ยินสองรอบ"

   หน้าค้นหาประกาศ "พบ 0 รายการ" ผ่าน live region ของตัวเองอยู่แล้ว ถ้า
   EmptyState ประกาศอีก ผู้ใช้จะได้ยินสองรอบติดกัน

   นี่คือปัญหารูปเดียวกับ `role="alert"` ของ `Banner` (§8.4) และระบบนี้
   ตอบเหมือนกันทุกครั้ง: **ทำเป็น opt-in ชื่อ `isLive` ค่าเริ่มต้น `false`**
   — ตั้ง `true` เฉพาะเมื่อที่ว่างโผล่มา**ตอบการกระทำของผู้ใช้** และไม่มี
   ใครประกาศแทนอยู่แล้ว

   ★★ **`title` ไม่เป็นหัวข้อโดยค่าเริ่มต้น** (Astryx ใช้ `headingLevel: 3`)

   เหตุผลเดียวกับ `Banner.titleAs` — ที่ว่างสามอันในหน้าเดียวจะฉีด `<h3>`
   สามอันเข้าไปปน `<h2>`/`<h3>` ของเนื้อหาจริง ทำให้ผู้ใช้ที่สำรวจหน้า
   ตามหัวข้อ (วิธีที่ใช้มากที่สุดวิธีหนึ่ง) เจอโครงที่อ่านไม่ออก

   ตั้ง `headingLevel` เฉพาะเมื่อที่ว่าง**แทนเนื้อหาของส่วนที่มีหัวข้อจริง**

   ⚠️ หนี้คำศัพท์ที่รู้ตัว: `Banner` ใช้ `titleAs` (รับ `'h2'|'h3'|'h4'`)
   ส่วนตัวนี้ใช้ `headingLevel` (รับ `1`–`6`) เพราะเป็นชื่อของ Astryx และ
   ตัวนี้สร้างใหม่จึงไม่มี call site เดิมให้พัง — **สองชื่อนี้หมายถึงสิ่ง
   เดียวกัน** ควรรวมเป็นชื่อเดียวในรอบถัดไป (บันทึกไว้ที่ D26)

   ★ **ต้องบอกทางออก ไม่ใช่แค่บอกว่าไม่มีอะไร**
   `description` มีไว้ตอบคำถาม "แล้วให้ฉันทำอะไร" — `SearchResult` เขียน
   คอมเมนต์นี้ไว้เองว่า "★ บอกทางออก ไม่ใช่แค่บอกว่าไม่พบ"
   ═══════════════════════════════════════════════════════════════════════════ */

export interface EmptyStateProps {
  /**
   * บรรทัดแรก — **บังคับ**
   *
   * บอกสิ่งที่เป็น ไม่ใช่คำขอโทษ · ✅ "ยังไม่มีรายการที่บันทึกไว้"
   */
  title: string;

  /**
   * รายละเอียด — **บอกทางออก** ไม่ใช่ขยายความว่าว่าง
   *
   * ✅ "กดปุ่มบันทึกบนรายการที่สนใจ เพื่อกลับมาดูภายหลัง"
   */
  description?: string;

  /**
   * ไอคอนหรือภาพประกอบเหนือหัวข้อ
   *
   * ธรรมเนียมของระบบคือ `<Icon name="…" size={32} />` — `Icon` ใส่
   * `aria-hidden` ให้เองเมื่อไม่มี `label` จึงเป็นของตกแต่งอยู่แล้ว
   */
  icon?: ReactNode;

  /** ปุ่มทางออก เช่น "ดูสินค้าทั้งหมด" */
  actions?: ReactNode;

  /**
   * ระดับหัวข้อของ `title` — ค่าเริ่มต้นคือ **ไม่เป็นหัวข้อ** (`<p>`)
   *
   * ⚠️ ต่างจาก Astryx ที่ตั้ง `3` ให้ · ดูหัวไฟล์
   */
  headingLevel?: 1 | 2 | 3 | 4 | 5 | 6;

  /**
   * ประกาศให้ screen reader ทันทีที่โผล่มา — ค่าเริ่มต้น `false`
   *
   * ⚠️ ตั้ง `true` **เฉพาะ** ตอนที่ว่างโผล่มาตอบการกระทำของผู้ใช้ และไม่มี
   * live region อื่นประกาศแทนอยู่แล้ว (ดูหัวไฟล์)
   */
  isLive?: boolean;

  /** ระยะกระชับสำหรับพื้นที่แคบ เช่นในการ์ด */
  isCompact?: boolean;

  className?: string;
}

/**
 * ที่ว่างที่ **บอกทางออก**
 *
 * ใช้กับ: ตะกร้าว่าง · รายการที่บันทึกว่าง · ค้นหาไม่พบ
 *
 * ไม่ใช้กับ: แถบที่ไม่ควร render เลยเมื่อว่าง (`Compare` เลือก `return null`
 * โดยเจตนา — แถบเปล่าที่มีแต่ความสูงทำให้เนื้อหาขยับ)
 */
export function EmptyState({
  title,
  description,
  icon,
  actions,
  headingLevel,
  isLive = false,
  isCompact = false,
  className,
}: EmptyStateProps) {
  const TitleTag = headingLevel ? (`h${headingLevel}` as const) : 'p';

  return (
    <div
      /* ★ ไม่มี role โดยค่าเริ่มต้น — ดูหัวไฟล์ว่าทำไมไม่ตาม Astryx */
      role={isLive ? 'status' : undefined}
      className={cn(
        'grid min-w-0 justify-items-center gap-3 text-center',
        isCompact ? 'px-3 py-6' : 'px-4 py-12',
        className,
      )}
    >
      {/* Icon ใส่ aria-hidden ให้เองเมื่อไม่มี label · text-fg-muted ที่นี่
         เพื่อให้ผู้เรียกไม่ต้องจำสีทุกครั้ง */}
      {icon && <span className="text-fg-muted">{icon}</span>}

      <TitleTag className="text-subtitle text-fg">{title}</TitleTag>

      {description && (
        /* ★ กว้างสุด --container-form — บรรทัดยาวเต็มจอกว้างอ่านยาก
           และข้อความไทยไม่มีช่องว่างระหว่างคำจึงยิ่งหาบรรทัดถัดไปยาก */
        <p className="max-w-(--container-form) text-body-sm text-fg-muted">{description}</p>
      )}

      {actions}
    </div>
  );
}
